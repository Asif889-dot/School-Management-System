// --- 1. ID Generation Logic ---
$year = date("Y");
$prefix = "TCH-" . $year . "-";

try {
    $idStmt = $pdo->prepare("SELECT employee_id FROM teachers WHERE employee_id LIKE ? ORDER BY employee_id DESC LIMIT 1");
    $idStmt->execute([$prefix . '%']);
    $lastId = $idStmt->fetchColumn();

    if ($lastId) {
        $number = intval(substr($lastId, -3));
        $autoGeneratedID = $prefix . str_pad($number + 1, 3, '0', STR_PAD_LEFT);
    } else {
        $autoGeneratedID = $prefix . '001';
    }
} catch (PDOException $e) {
    $autoGeneratedID = "ERROR";
}

// --- 2. Fetch existing teacher users that are not yet linked ---
try {
    // Get users with role 'teacher' who are not already linked to a teacher
    $userStmt = $pdo->query("
        SELECT u.id, u.reg_id, u.full_name, u.email 
        FROM users u 
        LEFT JOIN teachers t ON u.id = t.user_id 
        WHERE u.role = 'teacher' AND t.user_id IS NULL AND u.status = 'active'
        ORDER BY u.full_name ASC
    ");
    $availableUsers = $userStmt->fetchAll();
} catch (PDOException $e) {
    $availableUsers = [];
}

// --- 3. Fetch all teacher users for the dropdown (including already linked ones) ---
try {
    $allTeacherUsersStmt = $pdo->query("
        SELECT u.id, u.reg_id, u.full_name, u.email 
        FROM users u 
        WHERE u.role = 'teacher' AND u.status = 'active'
        ORDER BY u.full_name ASC
    ");
    $allTeacherUsers = $allTeacherUsersStmt->fetchAll();
} catch (PDOException $e) {
    $allTeacherUsers = [];
